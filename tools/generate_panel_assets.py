#!/usr/bin/env python3
"""Regenerate Arduino flash tables from the identified E02 firmware image."""
import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
IMAGE_SHA256 = "f32e594edaea183dce08023929aeb760b30dc8656accb35fa806d5e9137d96c7"
TABLES = (("glyphs", 0x4AFF8, 2560, 10),
          ("barPatterns", 0x4B9F8, 34 * 6, 6),
          ("markPatterns", 0x4BAF3, 34 * 5, 5))


def render(binary):
    if hashlib.sha256(binary).hexdigest() != IMAGE_SHA256:
        raise ValueError("The input must be the extracted CDJ-800MK2 E02 image")
    lines = ["// Generated by tools/generate_panel_assets.py; do not edit.",
             "// E02 SHA-256: " + IMAGE_SHA256,
             "// Literal firmware data; provenance is separate from driver source.",
             '#include "PanelAssets.h"', "namespace cdj800_detail {"]
    for name, offset, size, width in TABLES:
        lines.append(f"// Firmware file offset 0x{offset:x}; {size} bytes.")
        lines.append(f"const uint8_t {name}[{size}] CDJ800_FLASH = {{")
        data = binary[offset:offset + size]
        for start in range(0, size, width):
            lines.append("    " + ", ".join(f"0x{v:02x}" for v in data[start:start + width]) + ",")
        lines.append("};")
    lines.append("} // namespace cdj800_detail\n")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--firmware", type=Path, default=ROOT / "output/firmware/cdj800mk2/firmware.bin")
    parser.add_argument("--output", type=Path, default=ROOT / "lib/CDJ800SPI/src/PanelAssets.cpp")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render(args.firmware.read_bytes())
    if args.check:
        if args.output.read_text() != expected:
            raise SystemExit("Panel assets differ; regenerate them")
        print("PASS: all Arduino tables match the E02 image")
    else:
        args.output.write_text(expected)


if __name__ == "__main__":
    main()
